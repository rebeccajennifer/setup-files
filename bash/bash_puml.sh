#_______________________________________________________________________
# PlantUML Shortcuts
#_______________________________________________________________________

export PLANTUML_JAR=~/apps/plantuml.jar

#_______________________________________________________________________
# Export PlantUML diagrams
#_______________________________________________________________________
puml()
{
  java -jar $PLANTUML_JAR $1 $2
}

puml-svg()
{
  puml -tsvg $1
}

puml-png()
{
  puml -tpng $1
}


